from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

class ToolResult(BaseModel):
    """
    Standardized output format for all Copilot tools.
    """
    success: bool = Field(..., description="Whether the tool executed successfully.")
    data: Dict[str, Any] = Field(default_factory=dict, description="Data to be merged into the global resolver context.")
    error: Optional[str] = Field(None, description="Error message if success is False.")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Tool-specific metadata.")
    
    # Future UI Integration fields
    cards: List[Any] = Field(default_factory=list, description="Rich UI cards generated by the tool.")
    sources: List[Any] = Field(default_factory=list, description="Citations or deep links generated by the tool.")
    
    # Execution metrics
    execution_time: float = Field(default=0.0, description="Execution time in milliseconds.")
    tool_name: str = Field(default="", description="The name of the tool that generated this result.")
